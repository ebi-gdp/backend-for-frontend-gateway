package uk.ac.ebi.gdp.intervene.igs4eu.bff.router;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.web.reactive.function.server.RouterFunction;
import org.springframework.web.reactive.function.server.ServerResponse;

import static org.springframework.web.reactive.function.server.RouterFunctions.route;

@Configuration
public class BffRouterConfig {
    @Bean
    public RouterFunction<ServerResponse> sessionRoute(final SessionHandler sessionHandler) {
        return route()
                .GET("/session", sessionHandler::getSessionDetails)
                .build();
    }

    @Bean
    public SessionHandler sessionHandler() {
        return new SessionHandler();
    }
}
